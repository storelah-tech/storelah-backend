// Generates src/cms/admin/planGeometry.js (browser ES module) from the shared
// src/core/planGeometry.ts so the CMS editor and the API run the SAME geometry
// code (no hand-mirrored "keep in sync" copies). The output is committed;
// tests/e2e/floor-plan-precision.test.ts fails if it drifts from the source.
//
//   pnpm build:admin-geometry
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import ts from 'typescript';

export const ADMIN_GEOMETRY_SRC = path.join(__dirname, '..', 'src', 'core', 'planGeometry.ts');
export const ADMIN_GEOMETRY_OUT = path.join(__dirname, '..', 'src', 'cms', 'admin', 'planGeometry.js');

export function renderAdminGeometry(): string {
  const src = readFileSync(ADMIN_GEOMETRY_SRC, 'utf8');
  const { outputText } = ts.transpileModule(src, {
    compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ESNext, removeComments: false },
  });
  return (
    '// GENERATED by scripts/build-admin-geometry.ts from src/core/planGeometry.ts — DO NOT EDIT.\n' +
    '// Regenerate with `pnpm build:admin-geometry` after changing the source.\n' +
    outputText
  );
}

// Guarded: tests import renderAdminGeometry() in an ESM context with no `require`.
if (typeof require !== 'undefined' && require.main === module) {
  writeFileSync(ADMIN_GEOMETRY_OUT, renderAdminGeometry());
  console.log(`[build-admin-geometry] wrote ${path.relative(process.cwd(), ADMIN_GEOMETRY_OUT)}`);
}
